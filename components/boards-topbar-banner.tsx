import Image from "next/image";
import Link from "next/link";

/**
 * Баннер мини-игр, встроенный прямо в топбар (components/app-shell.tsx,
 * проп topbarBanner) — по разметке пользователя (красная рамка на
 * скриншоте): заполняет зазор между заголовком «Доски задач» и полем
 * поиска, а не отдельная полоса на всю ширину страницы (так было раньше,
 * см. историю правок в HANDOFF.md — пользователь дважды поправил
 * позиционирование, пока не показал скриншот с разметкой). Ширина 70%
 * от зазора между заголовком и поиском (-30% от full width той же
 * правкой), центрирована в этом зазоре (mx-auto — раньше была прижата
 * к левому краю).
 *
 * Высота раньше была жёстко h-[108px] (180px из замера рамки, затем -40%
 * по правке пользователя) — независимо от ширины. На большом экране зазор
 * между заголовком и поиском (а значит и 70% от него) становится намного
 * шире, а высота при этом оставалась той же 108px — получался куда более
 * широкий прямоугольник, чем исходное изображение (1442×322,
 * соотношение ≈4.48:1), и object-cover обрезал картинку сильнее, чем на
 * привычных экранах (жалоба «картинка баннера не должна обрезаться»).
 * Теперь вместо фиксированной высоты — aspect-[1442/322], точно
 * соотношение сторон самого файла: высота всегда пересчитывается из
 * ширины, форма контейнера всегда совпадает с картинкой, обрезки в
 * принципе быть не может (object-contain — на случай субпиксельного
 * рассинхрона от aspect-ratio, contain никогда не обрежет, максимум
 * оставит долю пикселя прозрачным полем). Заодно и «пропорционально
 * больше баннер» — на большом экране контейнер шире → aspect-ratio тянет
 * высоту пропорционально вверх, баннер целиком растёт, а не остаётся
 * приплюснутым к прежним 108px.
 *
 * По жалобе «при увеличении экрана растягивается в ширь и картинка
 * обрезается» (уже после перехода на aspect-ratio) добавляли
 * max-w-[900px] — потолок роста ширины. Но следующая правка
 * («баннер должен пропорционально изменяться») однозначно потребовала
 * ОБРАТНОЕ: рост без потолка, лишь бы форма не искажалась — то есть
 * сам max-width и был лишним/неверным решением предыдущей жалобы (та,
 * похоже, была именно про обрезку, которую уже чинит aspect-ratio, а не
 * про абсолютный размер). max-w убран: ширина = 70% от зазора без
 * верхнего предела, высота всегда пересчитывается из неё через
 * aspect-ratio — баннер растёт и уменьшается строго пропорционально
 * вместе с экраном на любом размере, кадрирования не будет никогда
 * (aspect-ratio держит форму контейнера идентичной форме файла).
 * Тонировка вдвое слабее прежней (opacity 0.5 → 0.25).
 * Яркость картинки ×1.5 (brightness 0.85 → 1.275), затем светлота
 * (opacity самой картинки — сквозь неё всё ещё просвечивал тёмный фон
 * страницы) тоже ×1.5 (0.45 → 0.675). Ещё раз «в 1.5 раза светлее»:
 * opacity картинки уже упирался в потолок (0.675×1.5>1), поэтому довели
 * до 1 (картинка больше не приглушена вообще) и вместо этого ×1.5
 * применили к brightness (1.275 → 1.9125), а раз именно тёмный градиент
 * поверх картинки теперь основной источник затемнения — ослабили и его
 * в 1.5 раза (0.15/0.45 → 0.10/0.30).
 * Серверный компонент (без "use client") — ничего интерактивного, кроме
 * самого Link, useTheme не нужен: рендерится только внутри AppShell,
 * который уже сам решает, показывать топбар (и этот проп) вообще или нет.
 */
export function BoardsTopbarBanner({ workspaceId }: { workspaceId: string }) {
  return (
    <Link
      href={`/w/${workspaceId}/game`}
      aria-label="Мини-игры: выберите, во что сыграть"
      title="Мини-игры: выберите, во что сыграть"
      className="relative mx-auto block aspect-[1442/322] w-[70%] overflow-hidden rounded-[16px]"
    >
      <Image
        src="/board-banner.png"
        alt=""
        fill
        sizes="(min-width: 1024px) 60vw, 100vw"
        className="object-contain"
        style={{ opacity: 1, filter: "saturate(0.75) brightness(1.9125)" }}
      />
      <div
        className="absolute inset-0"
        style={{ background: "var(--color-signal-deep)", mixBlendMode: "color", opacity: 0.25 }}
      />
      <div
        className="absolute inset-0"
        style={{ background: "linear-gradient(180deg, rgba(6,6,19,0.10) 0%, rgba(6,6,19,0.30) 100%)" }}
      />
    </Link>
  );
}
